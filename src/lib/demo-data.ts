/**
 * Zone spec: `number` = served with that flat surcharge, `false` = not served,
 * omitted = served at no surcharge. The builder always emits an entry for
 * EVERY zone in `codes`, so each service's coverage is fully explicit.
 */
type ZoneSpec = Partial<Record<ZoneCode, number | false>>;

function buildZones(codes: readonly ZoneCode[], spec: ZoneSpec): ZoneSurcharge[] {
  return codes.map((zone) => {
    const entry = spec[zone];
    if (entry === false) {
      return { zone, flat: 0, served: false };
    }
    return { zone, flat: entry ?? 0, served: true };
  });
}

/** Cross-border services list every UK zone and every Turkish zone. */
const gbTrZones = (spec: ZoneSpec): ZoneSurcharge[] =>
  buildZones([...GB_ZONES, ...TR_ZONES], spec);

const gbOnlyZones = (spec: ZoneSpec): ZoneSurcharge[] => buildZones(GB_ZONES, spec);
const trOnlyZones = (spec: ZoneSpec): ZoneSurcharge[] => buildZones(TR_ZONES, spec);

/** A band priced as a single fixed amount for any quantity inside it. */
function flatTier(
  unit: PricingUnit,
  fromQty: number,
  toQty: number | null,
  flatPrice: number,
): RateTier {
  return { unit, fromQty, toQty, flatPrice, pricePerUnit: null };
}

/** A band charged per unit on the portion of the quantity inside the band. */
function perUnitTier(
  unit: PricingUnit,
  fromQty: number,
  toQty: number | null,
  pricePerUnit: number,
): RateTier {
  return { unit, fromQty, toQty, flatPrice: null, pricePerUnit };
}

